import re
import shutil
from pathlib import Path, PurePosixPath
from tempfile import TemporaryDirectory
from urllib.parse import unquote

from django.contrib.staticfiles import finders
from django.core.files.storage import default_storage
from django.core.management.base import BaseCommand, CommandError
from django.test import RequestFactory, override_settings

from rowing.views import home

EXPORT_ORIGIN = "https://canoe-pages-export.invalid/"
EXPORT_URL = re.compile(re.escape(EXPORT_ORIGIN) + r'(?P<asset>(?:static|media)/[^\s"<>\\]+)')
MARKER = "Generated by manage.py export_pages\n"


def copy_asset(relative_url, directory):
    relative = PurePosixPath(unquote(relative_url))
    if relative.is_absolute() or ".." in relative.parts or len(relative.parts) < 2:
        raise CommandError(f"Недопустимый путь в экспорте: {relative_url}")

    kind, *parts = relative.parts
    name = "/".join(parts)
    destination = directory.joinpath(*relative.parts)
    destination.parent.mkdir(parents=True, exist_ok=True)

    if kind == "static":
        source = finders.find(name)
        if not source:
            raise CommandError(f"Статический файл не найден: {name}")
        shutil.copyfile(source, destination)
    else:
        try:
            with default_storage.open(name, "rb") as source, destination.open("wb") as target:
                shutil.copyfileobj(source, target)
        except FileNotFoundError as error:
            raise CommandError(f"Загруженный файл не найден: {name}") from error


class Command(BaseCommand):
    help = "Собрать публичную страницу, стили, скрипты и используемые загрузки для GitHub Pages."

    def add_arguments(self, parser):
        parser.add_argument("output", type=Path, help="Каталог для экспорта, например docs.")

    def handle(self, *args, **options):
        output = options["output"]
        marker = output / ".nojekyll"
        if output.exists() and (
            not output.is_dir()
            or (any(output.iterdir()) and (
                not marker.is_file() or marker.read_text(encoding="utf-8") != MARKER
            ))
        ):
            raise CommandError("Укажите пустой каталог или каталог, ранее созданный export_pages.")

        with override_settings(
            STATIC_URL=EXPORT_ORIGIN + "static/",
            MEDIA_URL=EXPORT_ORIGIN + "media/",
        ):
            response = home(RequestFactory().get("/"))
            html = response.content.decode(response.charset)
            assets = {match["asset"] for match in EXPORT_URL.finditer(html)}

        with TemporaryDirectory(prefix="canoe-pages-") as temporary:
            staging = Path(temporary)
            for asset in sorted(assets):
                copy_asset(asset, staging)

            page = EXPORT_URL.sub(lambda match: "./" + match["asset"], html)
            (staging / "index.html").write_text(page, encoding="utf-8")
            (staging / ".nojekyll").write_text(MARKER, encoding="utf-8")

            # Replace the generated asset trees so a removed upload is not published again.
            output.mkdir(parents=True, exist_ok=True)
            for name in ("static", "media"):
                previous = output / name
                if previous.is_dir():
                    shutil.rmtree(previous)
            shutil.copytree(staging, output, dirs_exist_ok=True)

        if options["verbosity"]:
            self.stdout.write(self.style.SUCCESS(f"Готово: {output / 'index.html'} ({len(assets)} файлов)."))
